from __future__ import annotations
from typing import Protocol
class RoleGateway(Protocol):
    def list(self,server_id:int)->list[dict]: ...
    def get(self,server_id:int,role:str)->dict: ...
    def create(self,server_id:int,body)->dict: ...
    def update(self,server_id:int,role:str,body)->dict: ...
    def password(self,server_id:int,role:str,password:str)->dict: ...
    def members(self,server_id:int,role:str)->list[dict]: ...
    def membership(self,server_id:int,role:str,member:str,grant:bool)->dict: ...

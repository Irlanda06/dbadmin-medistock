from typing import Protocol
class PrivilegeGateway(Protocol):
    def list(self,s:int,db:str,kind:str,schema:str|None,obj:str|None,role:str|None)->list[dict]: ...
    def effective(self,s:int,db:str,kind:str,schema:str|None,obj:str|None,role:str)->dict: ...
    def change(self,s:int,db:str,body,grant:bool)->dict: ...

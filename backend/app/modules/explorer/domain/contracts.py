from typing import Protocol
class ExplorerGateway(Protocol):
    def catalog(self, server_id:int, database:str, kind:str, schema:str|None=None)->list[dict]: ...
    def columns(self, server_id:int,database:str,schema:str,object_name:str)->list[dict]: ...
    def data(self,server_id:int,database:str,schema:str,object_name:str,limit:int,offset:int)->dict: ...
    def query(self,server_id:int,database:str,statement:str,limit:int)->dict: ...

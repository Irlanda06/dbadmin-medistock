from typing import Protocol
class DistributedGateway(Protocol):
    def extension(self,s:int,db:str)->dict: ...
    def servers(self,s:int,db:str)->list[dict]: ...
    def create_server(self,s:int,db:str,body)->dict: ...
    def mappings(self,s:int,db:str)->list[dict]: ...
    def mapping(self,s:int,db:str,body)->dict: ...
    def foreign_tables(self,s:int,db:str)->list[dict]: ...
    def foreign_table(self,s:int,db:str,body)->dict: ...
    def test(self,s:int,db:str,body)->dict: ...
    def view(self,s:int,db:str,body)->dict: ...
    def inventory(self,s:int,db:str,schema:str,view:str,limit:int,offset:int,details:bool)->dict: ...

from typing import Protocol
class RestoreRepository(Protocol):
    def create(self,backup_id:int,server_id:int,operation_id:int,database:str)->int: ...
    def get(self,restore_id:int)->dict: ...
    def list(self,server_id:int|None,status:str|None,limit:int,offset:int)->dict: ...
    def status(self,restore_id:int,status:str,verification:dict|None=None)->None: ...

import json, hashlib
from psycopg import sql
from app.core.exceptions import ValidationError,ConflictError
from app.modules._shared.common import ident,rows
from app.modules.restores.domain.contracts import RestoreRepository

class RestoreService:
    def __init__(self,repo:RestoreRepository,backups,access,tools): self.repo=repo;self.backups=backups;self.access=access;self.tools=tools
    @staticmethod
    def public(row):
        names={'backup_id':'backupId','target_server_id':'targetServerId','operation_id':'operationId','target_database':'targetDatabase','created_at':'createdAt','finished_at':'finishedAt'}
        result={names.get(k,k):v for k,v in row.items() if k!='verification_json'}
        result['verification']=json.loads(row['verification_json']) if row['verification_json'] else None
        return result
    def get(self,rid): return self.public(self.repo.get(rid))
    def list(self,*args):
        p=self.repo.list(*args);p['items']=[self.public(x) for x in p['items']];return p
    def verification(self,rid):
        record=self.get(rid);return {'restoreId':rid,'status':record['status'],'verification':record['verification']}
    def validate(self,body):
        backup=self.backups.repo.get(body.backup_id);path=self.backups.path(body.backup_id)
        ident(body.target_database)
        profile=self.access.profiles.get_server(body.target_server_id)
        if body.target_database.lower() in {'postgres','template0','template1','medistock',profile.database_name.lower(),backup['database_name'].lower()}:
            raise ValidationError('Selecciona una base nueva de prueba, diferente a las operativas')
        self.tools.executable('pg_restore' if backup['format']=='CUSTOM' else 'psql')
        # Only backups generated by this application, not uploaded scripts.
        with path.open('rb') as file: digest=hashlib.file_digest(file,'sha256').hexdigest()
        record=self.access.history.get_operation(backup['operation_id'])
        if not record.result or record.result.get('sha256')!=digest: raise ConflictError('El SHA-256 del respaldo no coincide')
        with self.access.connection(body.target_server_id,'postgres') as c:
            if c.execute('SELECT 1 FROM pg_database WHERE datname=%s',(body.target_database,)).fetchone(): raise ConflictError('La base destino ya existe')
            role=c.execute('SELECT rolcreatedb OR rolsuper AS allowed FROM pg_roles WHERE rolname=current_user').fetchone()
            if not role['allowed']: raise ValidationError('La cuenta necesita CREATEDB')
        return {'valid':True,'backupId':body.backup_id,'targetServerId':body.target_server_id,'targetDatabase':body.target_database,'warning':'Un respaldo selectivo puede requerir dependencias no incluidas' if backup['scope']!='DATABASE' else None}
    def enqueue(self,body):
        self.validate(body)
        op=self.access.history.enqueue(self.access.context(body.target_server_id,body.target_database,'RESTORE',body.target_database))
        try: rid=self.repo.create(body.backup_id,body.target_server_id,op,body.target_database)
        except Exception as exc: self.access.history.fail(op,exc);raise
        return self.get(rid)
    def run(self,rid):
        from types import SimpleNamespace
        r=self.repo.get(rid);op=r['operation_id'];s=r['target_server_id'];db=r['target_database'];created=False
        try:
            self.access.history.start(op);self.repo.status(rid,'RUNNING')
            self.validate(SimpleNamespace(backup_id=r['backup_id'],target_server_id=s,target_database=db))
            backup=self.backups.repo.get(r['backup_id']);path=self.backups.path(r['backup_id'])
            # CREATE DATABASE is atomic: an existing database causes an error, never overwrite.
            with self.access.connection(s,'postgres',autocommit=True) as c:
                c.execute(sql.SQL('CREATE DATABASE {} TEMPLATE template0').format(ident(db)))
            created=True
            if backup['scope']=='TABLE':
                with self.access.connection(s,db) as c:
                    c.execute(sql.SQL('CREATE SCHEMA IF NOT EXISTS {}').format(ident(backup['schema_name'])))
            creds=self.access.credentials(s,db)
            if backup['format']=='CUSTOM': self.tools.run('pg_restore',['--exit-on-error','--single-transaction','--no-owner','--no-privileges',str(path)],creds)
            else: self.tools.run('psql',['-X','--set=ON_ERROR_STOP=1','--single-transaction','--file='+str(path)],creds)
            with self.access.connection(s,db) as c:
                tables=rows(c,"SELECT schemaname AS schema,tablename AS name FROM pg_tables WHERE schemaname NOT IN ('pg_catalog','information_schema') ORDER BY 1,2")
                for t in tables: t['rowCount']=c.execute(sql.SQL('SELECT count(*) AS n FROM {}').format(ident(t['schema'],t['name']))).fetchone()['n']
            verification={'database':db,'tableCount':len(tables),'tables':tables,'databaseCreated':True}
        except Exception as exc:
            self.repo.status(rid,'FAILED',{'databaseCreated':created,'warning':'Si se creó la base de prueba, se conserva para inspección; no se elimina automáticamente.'});self.access.history.fail(op,exc);return
        self.repo.status(rid,'SUCCEEDED',verification);self.access.history.succeed(op,{'restoreId':rid,'tableCount':len(tables),'database':db})

from typing import Protocol
class BackupRepository(Protocol):
    def create(self, values:dict)->int: ...
    def get(self, backup_id:int)->dict: ...
    def list(self,server_id:int|None,status:str|None,limit:int,offset:int)->dict: ...
    def status(self,backup_id:int,status:str,size:int=0)->None: ...
